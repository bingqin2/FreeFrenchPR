export type StringKey = keyof typeof strings;

export function useT() {
  const [settings] = useSettings();
  const lang = settings.lang;
  const t = (key: StringKey) => strings[key][lang === 'zh' ? 1 : 0];
  return { t, lang };
}

/** Read an en/zh field pair from content, e.g. pick(lesson, 'title', lang) → titleEn | titleZh. */
export function pick<T extends object>(obj: T, base: string, lang: 'en' | 'zh'): string {
  const rec = obj as Record<string, unknown>;
  return (rec[base + (lang === 'zh' ? 'Zh' : 'En')] ?? rec[base + 'En'] ?? '') as string;
}

/** For {en, zh} objects. */
export const tr = (o: { en: string; zh: string }, lang: 'en' | 'zh') => (lang === 'zh' ? o.zh : o.en);
